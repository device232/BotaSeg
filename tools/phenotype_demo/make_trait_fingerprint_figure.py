def draw_leaf_shape_complexity(ax: plt.Axes, leaf_traits: pd.DataFrame) -> None:
    groups = ["Round-leaf", "Lobed-leaf"]
    dark_colors = [ROUND_DARK, FLOWER_DARK]
    light_colors = [ROUND_LIGHT, FLOWER_LIGHT]
    values = [
        leaf_traits.loc[leaf_traits["leaf_type"] == group, "leaf_shape_complexity"].groupby(
            leaf_traits.loc[leaf_traits["leaf_type"] == group, "sample"]
        ).median().to_numpy()
        for group in groups
    ]
    jitter_rng = np.random.default_rng(42)
    summary_width = 0.28
    for position, (group_values, color) in enumerate(zip(values, dark_colors)):
        q1, median, q3 = np.percentile(group_values, [25, 50, 75])
        group_min, group_max = np.min(group_values), np.max(group_values)
        ax.vlines(position, group_min, group_max, color=color, linewidth=0.8, alpha=0.75, zorder=1)
        ax.add_patch(
            Rectangle(
                (position - summary_width / 2, q1),
                summary_width,
                q3 - q1,
                facecolor=light_colors[position],
                edgecolor=color,
                linewidth=1.05,
                zorder=2,
            )
        )
        ax.hlines(median, position - summary_width / 2, position + summary_width / 2,
                  color="#333333", linewidth=1.8, zorder=4)
        jitter = jitter_rng.uniform(-0.08, 0.08, size=len(group_values))
        ax.scatter(position + jitter, group_values, s=32, color=color, edgecolor="#222222", linewidth=0.45, zorder=5)
    ax.set_xlim(-0.5, 1.5)
    ax.set_xticks([0, 1], ["Round-leaf\n(n = 5)", "Lobed-leaf\n(n = 5)"], fontsize=8.2)
    ax.set_ylabel("Leaf shape complexity index,\n" + r"$P^2/(4\pi A)$", fontsize=8.8)
    ax.set_title("c1. Leaf shape complexity", fontsize=10.4, loc="left", pad=8, fontweight="bold")
    ax.tick_params(axis="y", labelsize=8.0, length=2)
    ax.grid(axis="y", color="#D5DADD", lw=0.55, zorder=0)


def draw_vertical_posture_profile(
    ax: plt.Axes,
    profiles: pd.DataFrame,
) -> None:
    """Plot all plants together without group-wise interpolation or smoothing."""
    individual_colors = {
        "Round-leaf": ["#4C8C2B", "#5E9E39", "#3D7A28", "#72A94B", "#2F6E25"],
        "Lobed-leaf": ["#7B4AA3", "#8E61B0", "#69408F", "#9C73BF", "#5F3781"],
    }
    markers = {"Round-leaf": "o", "Lobed-leaf": "s"}
    for group in ("Round-leaf", "Lobed-leaf"):
        group_profiles = profiles.loc[profiles["leaf_type"] == group]
        for plant_index, (_, plant_profile) in enumerate(group_profiles.groupby("sample")):
            plant_profile = plant_profile.sort_values("normalized_insertion_height")
            ax.plot(
                plant_profile["normalized_insertion_height"],
                plant_profile["effective_posture_angle_deg"],
                color=individual_colors[group][plant_index],
                alpha=0.76,
                lw=1.2,
                marker=markers[group],
                markersize=2.8,
                markerfacecolor="white",
                markeredgewidth=0.75,
                markeredgecolor=individual_colors[group][plant_index],
                zorder=2,
                clip_on=False,
            )
    # Preserve complete endpoint markers at normalized heights 0 and 1.
    ax.set_xlim(-0.055, 1.055)
    ax.set_xticks(np.linspace(0, 1, 6))
    ax.set_ylim(0, 180)
    ax.tick_params(labelsize=7.3, length=2)
    ax.grid(color="#D5DADD", lw=0.55)
    ax.set_title("c2. Vertical effective leaf-posture profiles", fontsize=9.3, loc="left", pad=8, fontweight="bold")
    ax.set_xlabel("Normalized leaf insertion height", fontsize=8.3, labelpad=7)
    ax.set_ylabel("Effective leaf posture angle (deg)", fontsize=8.0, labelpad=5)


def crop_rgb_canvas(image: np.ndarray) -> np.ndarray:
    """Remove the empty viewport around an RGB point cloud without clipping it."""
    rgb = image[..., :3]
    white_threshold = 245 / 255 if np.issubdtype(rgb.dtype, np.floating) else 245
    occupied = np.any(rgb < white_threshold, axis=2)
    rows, columns = np.where(occupied)
    if rows.size == 0:
        return image

    pad = max(16, int(0.06 * max(np.ptp(rows) + 1, np.ptp(columns) + 1)))
    y0 = max(0, rows.min() - pad)
    y1 = min(image.shape[0], rows.max() + pad + 1)
    x0 = max(0, columns.min() - pad)
    x1 = min(image.shape[1], columns.max() + pad + 1)
    return image[y0:y1, x0:x1]


