def draw_matrix(
    ax: plt.Axes,
    values: pd.DataFrame,
    xlabels: list[str],
    ylabels: list[str],
    cmap: LinearSegmentedColormap,
    *,
    cell_fontsize: float = 8.0,
    row_group_boundary: int | None = None,
    column_group_boundary: int | None = None,
) -> mpl.image.AxesImage:
    limit = max(2.2, float(np.nanmax(np.abs(values.to_numpy()))) + 0.1)
    image = ax.imshow(values.to_numpy(), aspect="auto", cmap=cmap, vmin=-limit, vmax=limit)
    ax.set_xticks(np.arange(values.shape[1]), xlabels)
    ax.set_yticks(np.arange(values.shape[0]), ylabels)
    ax.tick_params(length=0, pad=4)
    for x in np.arange(-0.5, values.shape[1], 1):
        ax.axvline(x, color="white", lw=0.5)
    for y in np.arange(-0.5, values.shape[0], 1):
        ax.axhline(y, color="white", lw=0.5)
    if row_group_boundary is not None:
        ax.axhline(row_group_boundary - 0.5, color="#4D5963", lw=1.2)
    if column_group_boundary is not None:
        ax.axvline(column_group_boundary - 0.5, color="#4D5963", lw=1.2)
    for row in range(values.shape[0]):
        for col in range(values.shape[1]):
            value = values.iloc[row, col]
            ax.text(
                col,
                row,
                f"{value:.1f}",
                ha="center",
                va="center",
                fontsize=cell_fontsize,
                color="white" if abs(value) >= 1.25 else "#20262B",
            )
    return image


