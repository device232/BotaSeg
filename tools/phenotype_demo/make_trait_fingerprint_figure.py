def zscore(frame: pd.DataFrame) -> pd.DataFrame:
    std = frame.std(axis=0, ddof=0).replace(0, 1.0)
    return (frame - frame.mean(axis=0)) / std


def resolve_project_path(path_value: str) -> Path:
    """Resolve defaults from either the project root or the Pointcept subdirectory."""
    candidate = Path(path_value)
    if candidate.exists() or candidate.is_absolute():
        return candidate
    project_root = Path(__file__).resolve().parents[3]
    return project_root / candidate


def leaf_type(sample: str) -> str:
    return "Round-leaf" if sample in ROUND_LEAF_SAMPLES else "Lobed-leaf"


def derive_targeted_indices(
    plant_traits: pd.DataFrame,
    leaf_traits: pd.DataFrame,
    posture_traits: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """Compute targeted indices from predicted local insertion and whole-leaf posture."""
    valid_leaf = leaf_traits.copy()
    valid_leaf["leaf_shape_complexity"] = (
        valid_leaf["leaf_perimeter"] ** 2
        / (4 * np.pi * valid_leaf["leaf_area_mesh_surface"])
    )
    valid_leaf = valid_leaf.loc[
        np.isfinite(valid_leaf["leaf_perimeter"])
        & np.isfinite(valid_leaf["leaf_area_mesh_surface"])
        & (valid_leaf["leaf_perimeter"] > 0)
        & (valid_leaf["leaf_area_mesh_surface"] > 0)
        & np.isfinite(valid_leaf["leaf_shape_complexity"])
    ].copy()
    valid_leaf["leaf_type"] = valid_leaf["sample"].map(leaf_type)
    leaf_shape = valid_leaf.groupby("sample")["leaf_shape_complexity"].median()

    profiles = []
    posture_metrics = pd.DataFrame(
        index=plant_traits.index,
        columns=[
            "upper_leaf_uprightness",
            "middle_leaf_uprightness",
            "lower_leaf_openness",
            "vertical_uprightness_gradient",
            "mean_leaf_droop_index",
        ],
        dtype=float,
    )
    for sample in plant_traits.index:
        plant_posture = posture_traits.loc[posture_traits["sample"] == sample].copy()
        plant_posture = plant_posture.loc[
            np.isfinite(plant_posture["leaf_insertion_height"])
            & np.isfinite(plant_posture["effective_leaf_uprightness"])
        ].copy()
        if plant_posture.empty:
            continue
        height_min = plant_posture["leaf_insertion_height"].min()
        height_range = plant_posture["leaf_insertion_height"].max() - height_min
        if not np.isfinite(height_range) or height_range <= 0:
            continue
        plant_posture["normalized_insertion_height"] = (
            plant_posture["leaf_insertion_height"] - height_min
        ) / height_range
        plant_posture = plant_posture.sort_values("normalized_insertion_height").reset_index(drop=True)
        plant_posture["sample"] = sample
        plant_posture["leaf_type"] = leaf_type(sample)
        profiles.append(plant_posture)

        n_leaves = len(plant_posture)
        lower, middle, upper = np.array_split(np.arange(n_leaves), 3)
        uprightness = plant_posture["effective_leaf_uprightness"]
        # 1 - U_eff may exceed one when a lower leaf extends downward; this is intentional.
        posture_metrics.loc[sample, "upper_leaf_uprightness"] = uprightness.iloc[upper].mean()
        posture_metrics.loc[sample, "middle_leaf_uprightness"] = uprightness.iloc[middle].mean()
        posture_metrics.loc[sample, "lower_leaf_openness"] = (1 - uprightness.iloc[lower]).mean()
        posture_metrics.loc[sample, "mean_leaf_droop_index"] = plant_posture["leaf_droop_index"].mean()
        if n_leaves >= 3 and plant_posture["normalized_insertion_height"].nunique() >= 2:
            posture_metrics.loc[sample, "vertical_uprightness_gradient"] = float(
                theilslopes(
                    uprightness.to_numpy(),
                    plant_posture["normalized_insertion_height"].to_numpy(),
                )[0]
            )

    profile_frame = pd.concat(profiles, ignore_index=True) if profiles else pd.DataFrame()
    targeted_raw = pd.DataFrame(index=plant_traits.index)
    base_standardized = zscore(plant_traits)
    targeted_raw["leaf_expansion"] = base_standardized[
        ["leaf_area_mesh_surface_mean", "leaf_area_mesh_surface_total", "leaf_length_mean"]
    ].mean(axis=1)
    targeted_raw["organ_abundance"] = base_standardized["leaf_count"]
    targeted_raw["leaf_shape_complexity"] = leaf_shape.reindex(plant_traits.index)
    targeted_raw = targeted_raw.join(
        posture_metrics[["upper_leaf_uprightness", "lower_leaf_openness", "vertical_uprightness_gradient"]]
    )
    targeted_z = zscore(targeted_raw)
    return targeted_raw, targeted_z, valid_leaf, profile_frame, posture_metrics


def add_card(fig: plt.Figure, subplot_spec) -> mpl.transforms.Bbox:
    """Add a restrained rounded frame behind one of the four content panels."""
    position = subplot_spec.get_position(fig)
    inset = 0.0035
    card = FancyBboxPatch(
        (position.x0 + inset, position.y0 + inset),
        position.width - 2 * inset,
        position.height - 2 * inset,
        boxstyle="round,pad=0.004,rounding_size=0.008",
        transform=fig.transFigure,
        facecolor="white",
        edgecolor=CARD_EDGE,
        linewidth=0.8,
        zorder=-5,
        clip_on=False,
    )
    fig.add_artist(card)
    return position


